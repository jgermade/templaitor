// TypeScript declarations of a project's data contracts (`templaitor types`, compile, engine.types()).
import { listTemplates, readTemplate } from './project.js'
import { contractOf } from './message.js'
import { toTypeScript } from '../shared/contract.js'

/** `export interface <Name>Data` per template + `TemplateData` (id → data) */
export function projectTypes(project) {
  const templates = listTemplates(project).map(t => ({ id: t.id, contract: contractOf(readTemplate(project, t.id).mjml) }))
  return toTypeScript(templates, {
    header: `// Generated by templaitor from the data contracts of "${project.name}" (data: in each template's frontmatter).\n// Do not edit: run \`templaitor types\` again after changing a contract.`,
  })
}
